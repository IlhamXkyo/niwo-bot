async function handler(m, { sock }) {
    if (!m.quoted) {
        return sendReply(m, '⚠️ *Reply pesan yang ingin dihapus!*')
    }

    const quotedSender = m.quoted.sender || m.quoted.key?.participant
    const botJid = sock.user?.id?.split(':')[0] + '@s.whatsapp.net'
    const isOwnMessage = m.quoted.key?.fromMe || quotedSender === m.sender
    const isBotMessage = quotedSender === botJid || m.quoted.key?.fromMe

    if (!isOwnMessage && !isBotMessage) {
        if (!m.isBotAdmin) {
            return sendReply(m, '⚠️ *Bot harus jadi admin untuk hapus pesan orang lain!*')
        }
        if (!m.isAdmin && !m.isOwner) {
            return sendReply(m, '⚠️ *Hanya admin yang bisa hapus pesan orang lain!*')
        }
    }

    try {
        const key = {
            remoteJid: m.chat,
            id: m.quoted.key.id,
            fromMe: m.quoted.key.fromMe,
            participant: quotedSender
        }

        await sock.sendMessage(m.chat, { delete: key })
        await m.react?.('✅')

    } catch (err) {
        if (err.message?.includes('not found') || err.message?.includes('forbidden')) {
            await sendReply(m, '❌ *Gagal menghapus!*\n> Pesan mungkin sudah dihapus atau terlalu lama.')
        } else {
            await m.react?.('❌')
        }
    }
}

export default { config, handler };
